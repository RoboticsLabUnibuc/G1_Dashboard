class DashboardTelemetryPublisher:
    """Best-effort, non-blocking localhost UDP telemetry publisher.

    The live control loop only submits the newest immutable snapshot. JSON
    serialization and UDP send happen on a daemon thread, so a slow dashboard
    consumer or temporary socket pressure cannot stall the robot control loop.
    There is deliberately no dashboard heartbeat in the safety path.
    """

    def __init__(self, host: str, port: int, frequency_hz: float) -> None:
        self.host = str(host)
        self.port = int(port)
        self.frequency_hz = float(frequency_hz)
        self.period_s = 1.0 / self.frequency_hz
        self._next_send = 0.0
        self._sequence = 0
        self._sent = 0
        self._dropped = 0
        self._last_error: Optional[str] = None

        self._socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self._socket.setblocking(False)
        self._latest_lock = threading.Lock()
        self._latest_packet: Optional[dict[str, object]] = None
        self._wake = threading.Event()
        self._stop = threading.Event()
        self._thread = threading.Thread(
            target=self._send_loop,
            name="g1-dashboard-telemetry-udp",
            daemon=True,
        )
        self._thread.start()

    @property
    def next_sequence(self) -> int:
        return self._sequence

    @property
    def sent_count(self) -> int:
        return self._sent

    @property
    def dropped_count(self) -> int:
        return self._dropped

    @property
    def last_error(self) -> Optional[str]:
        return self._last_error

    def due(self, now: float) -> bool:
        return now >= self._next_send

    def publish(self, now: float, packet: dict[str, object]) -> None:
        """Submit newest telemetry without waiting for serialization/network."""
        self._next_send = now + self.period_s
        self._sequence += 1
        with self._latest_lock:
            if self._latest_packet is not None:
                # A newer control-loop snapshot superseded one the worker had
                # not consumed yet. Dropping stale telemetry is intentional.
                self._dropped += 1
            self._latest_packet = packet
        self._wake.set()

    def _send_loop(self) -> None:
        while not self._stop.is_set():
            self._wake.wait(timeout=0.5)
            self._wake.clear()

            with self._latest_lock:
                packet = self._latest_packet
                self._latest_packet = None

            if packet is None:
                continue

            try:
                encoded = json.dumps(
                    packet,
                    separators=(",", ":"),
                    allow_nan=False,
                ).encode("utf-8")
                if len(encoded) > 65507:
                    raise ValueError(
                        f"telemetry datagram too large: {len(encoded)} bytes"
                    )
                self._socket.sendto(encoded, (self.host, self.port))
                self._sent += 1
                self._last_error = None
            except (BlockingIOError, InterruptedError):
                self._dropped += 1
            except Exception as exc:
                # Telemetry failure must never affect live robot control.
                self._dropped += 1
                self._last_error = f"{type(exc).__name__}: {exc}"

    def close(self) -> None:
        self._stop.set()
        self._wake.set()
        self._thread.join(timeout=0.5)
        try:
            self._socket.close()
        except Exception:
            pass


def reset_arm_ik_session_state(
    arm_ik: G1_29_ArmIK,
    current_q: np.ndarray,
    *,
    reason: str,
) -> None:
    """Clear IK history that must not cross a clutch/hold boundary.

    ``G1_29_ArmIK.solve_ik`` overwrites ``init_data`` from ``current_q`` on
    every call, but its ``WeightedMovingFilter`` persists for the lifetime of
    the process. Without clearing that queue, the first IK results after a new
    ``c`` engagement are blended with joint solutions from the previous XR
    session.

    We intentionally reset only session history. The IK objective, gains,
    ownership weight, and discontinuity thresholds are unchanged.
    """
    seed = np.asarray(current_q, dtype=float).reshape(-1)
    if seed.shape != (14,) or not np.isfinite(seed).all():
        raise ValueError("IK reset requires a finite 14-joint measured seed")

    smooth_filter = getattr(arm_ik, "smooth_filter", None)
    data_queue = getattr(smooth_filter, "_data_queue", None)
    if smooth_filter is None or not isinstance(data_queue, list):
        raise RuntimeError(
            "G1_29_ArmIK smooth_filter does not expose the expected queue"
        )

    old_queue_len = len(data_queue)
    data_queue.clear()
    smooth_filter._filtered_data = seed.copy()
    arm_ik.init_data = seed.copy()

    LOG.info(
        "IK SESSION RESET (%s): cleared %d stale smoothing sample(s); "
        "seeded from measured arm q.",
        reason,
        old_queue_len,
    )


def update_xr_command(
    *,
    arm_ik: G1_29_ArmIK,
    arm_ctrl: SafeArmSdkController,
    xr_state: XrCommandState,
    tele_data: object,
    translation_bias: np.ndarray,
    current_q: np.ndarray,
    current_dq: np.ndarray,
    args: argparse.Namespace,
) -> tuple[bool, str]:
    live_left = np.asarray(
        tele_data.left_wrist_pose,
        dtype=float,
    ).copy()
    live_right = np.asarray(
        tele_data.right_wrist_pose,
        dtype=float,
    ).copy()

    registered_left = apply_translation_bias(
        live_left,
        translation_bias,
    )
    registered_right = apply_translation_bias(
        live_right,
        translation_bias,
    )

    registered_left, registered_right = apply_bimanual_inward_offset(
        registered_left,
        registered_right,
        args.bimanual_inward_offset_m,
    )

    xr_state.registered_left = registered_left.copy()
    xr_state.registered_right = registered_right.copy()

    (
        guarded_left,
        guarded_right,
        last_good_left,
        last_good_right,
        pending_left,
        pending_right,
        pending_count,
        left_rejected,
        right_rejected,
        pair_reacquired,
    ) = update_guarded_pair(
        registered_left,
        registered_right,
        xr_state.last_good_left,
        xr_state.last_good_right,
        xr_state.left_pending,
        xr_state.right_pending,
        max(xr_state.left_pending_count, xr_state.right_pending_count),
        args.tracking_jump_m,
        args.tracking_jump_deg,
        args.tracking_reacquire_frames,
    )

    xr_state.guarded_left = guarded_left
    xr_state.guarded_right = guarded_right
    xr_state.last_good_left = last_good_left
    xr_state.last_good_right = last_good_right
    xr_state.left_pending = pending_left
    xr_state.right_pending = pending_right
    xr_state.left_pending_count = pending_count
    xr_state.right_pending_count = pending_count
    xr_state.guard_rejected_left = left_rejected
    xr_state.guard_rejected_right = right_rejected
    xr_state.pair_reacquired = pair_reacquired
    xr_state.guard_active = left_rejected or right_rejected

    if pair_reacquired:
        LOG.info(
            "Stable bimanual tracking pair accepted after %d-frame "
            "reacquisition.",
            args.tracking_reacquire_frames,
        )

    now = time.monotonic()
    command_dt = float(
        np.clip(now - xr_state.last_command_time, 0.005, 0.10)
    )
    xr_state.last_command_time = now

    left_command = rate_limit_pose(
        xr_state.last_left_command,
        guarded_left,
        command_dt,
        args.max_wrist_speed,
        args.max_wrist_rotation_speed_deg,
    )
    right_command = rate_limit_pose(
        xr_state.last_right_command,
        guarded_right,
        command_dt,
        args.max_wrist_speed,
        args.max_wrist_rotation_speed_deg,
    )

    xr_state.last_left_command = left_command.copy()
    xr_state.last_right_command = right_command.copy()

    try:
        solution_q, solution_tau = arm_ik.solve_ik(
            left_command,
            right_command,
            current_q,
            current_dq,
        )
    except Exception as exc:
        return False, f"IK exception: {exc}"

    solution_q = np.asarray(solution_q, dtype=float).reshape(-1)
    solution_tau = np.asarray(solution_tau, dtype=float).reshape(-1)

    xr_state.last_solution_q = solution_q.copy()
    xr_state.last_solution_tau = solution_tau.copy()

    if (
        solution_q.shape != (14,)
        or solution_tau.shape != (14,)
        or not np.isfinite(solution_q).all()
        or not np.isfinite(solution_tau).all()
    ):
        return False, "IK returned an invalid 14-joint command"

    if xr_state.initial_ik_seed_pending:
        # The first IK solution after alignment initializes the user target;
        # it is not a branch jump. Ownership is still zero at this point.
        initial_ik_offset = float(
            np.max(np.abs(solution_q - current_q))
        )
        if initial_ik_offset > args.max_initial_ik_offset_rad:
            return (
                False,
                "initial IK offset "
                f"{initial_ik_offset:.3f} rad exceeds "
                f"{args.max_initial_ik_offset_rad:.3f} rad",
            )

        arm_ctrl.set_target(solution_q, solution_tau)
        xr_state.initial_ik_seed_pending = False
        LOG.info(
            "Initial IK target seeded at weight zero; "
            "max joint offset=%.3f rad.",
            initial_ik_offset,
        )
        return True, "ok"

    previous_target = arm_ctrl.get_target_q()
    ik_target_jump = float(
        np.max(np.abs(solution_q - previous_target))
    )
    if ik_target_jump > args.max_ik_target_jump_rad:
        return (
            False,
            "IK target discontinuity "
            f"{ik_target_jump:.3f} rad exceeds "
            f"{args.max_ik_target_jump_rad:.3f} rad",
        )

    arm_ctrl.set_target(solution_q, solution_tau)
    return True, "ok"



def finite_hand_landmarks(
    value: object,
) -> tuple[bool, Optional[np.ndarray], str]:
    try:
        data = np.asarray(value, dtype=float)
    except Exception as exc:
        return False, None, f"conversion failed: {exc}"

    if data.shape != (25, 3):
        return False, None, f"shape={data.shape}, expected (25, 3)"
    if not np.isfinite(data).all():
        return False, None, "contains NaN/Inf"

    extents = np.ptp(data, axis=0)
    max_extent = float(np.max(extents))
    if max_extent < 0.025:
        return False, None, f"collapsed landmarks, extent={max_extent:.4f} m"

    return True, data.copy(), "ok"


def normalize_inspire_target(raw_target: np.ndarray) -> np.ndarray:
    raw = np.asarray(raw_target, dtype=float).copy()
    if raw.shape != (6,):
        raise ValueError(f"Expected six Inspire targets, got {raw.shape}")

    result = np.empty(6, dtype=float)
    result[:4] = (1.7 - raw[:4]) / 1.7
    result[4] = (0.5 - raw[4]) / 0.5
    result[5] = (1.3 - raw[5]) / 1.4
    return np.clip(result, 0.0, 1.0)


def rate_limit_finger(
    current: np.ndarray,
    target: np.ndarray,
    max_speed_per_s: float,
    dt: float,
) -> np.ndarray:
    step = max(0.0, float(max_speed_per_s)) * max(0.0, float(dt))
    return current + np.clip(target - current, -step, step)


class SharedHandTracking:
    """Thread-safe copy of the latest TeleVuer hand landmarks.

    Only the main arm loop calls TeleVuer. The finger worker consumes
    copies from this cache, so no second TeleVuer instance or concurrent
    get_tele_data() call is created.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._left: Optional[np.ndarray] = None
        self._right: Optional[np.ndarray] = None
        self._motion_ready = False
        self._received_monotonic = 0.0
        self._sequence = 0

    def update(self, tele_data: object) -> None:
        left_value = getattr(tele_data, "left_hand_pos", None)
        right_value = getattr(tele_data, "right_hand_pos", None)

        try:
            left = np.asarray(left_value, dtype=float).copy()
        except Exception:
            left = None
        try:
            right = np.asarray(right_value, dtype=float).copy()
        except Exception:
            right = None

        with self._lock:
            self._left = left
            self._right = right
            self._motion_ready = bool(
                getattr(tele_data, "motion_data_ready", False)
            )
            self._received_monotonic = time.monotonic()
            self._sequence += 1

    def snapshot(
        self,
    ) -> tuple[
        Optional[np.ndarray],
        Optional[np.ndarray],
        bool,
        float,
        int,
    ]:
        with self._lock:
            left = None if self._left is None else self._left.copy()
            right = None if self._right is None else self._right.copy()
            motion_ready = self._motion_ready
            received = self._received_monotonic
            sequence = self._sequence

        age = (
            time.monotonic() - received
            if received > 0.0
            else math.inf
        )
        return left, right, motion_ready, age, sequence


class InspireDfxIo:
    def __init__(self) -> None:
        self.publisher = ChannelPublisher(
            INSPIRE_COMMAND_TOPIC,
            MotorCmds_,
        )
        self.publisher.Init()

        self.subscriber = ChannelSubscriber(
            INSPIRE_STATE_TOPIC,
            MotorStates_,
        )
        self.subscriber.Init()

        self.message = MotorCmds_()
        self.message.cmds = [
            unitree_go_msg_dds__MotorCmd_()
            for _ in range(INSPIRE_MOTOR_COUNT)
        ]

        self.last_state: Optional[np.ndarray] = None
        self.last_state_time = 0.0
        self.write_count = 0
        self.last_write_exception: Optional[Exception] = None

    def publish(self, left: np.ndarray, right: np.ndarray) -> None:
        left_command = np.clip(
            np.asarray(left, dtype=float),
            0.0,
            1.0,
        ).copy()
        right_command = np.clip(
            np.asarray(right, dtype=float),
            0.0,
            1.0,
        ).copy()
        if left_command.shape != (6,) or right_command.shape != (6,):
            raise ValueError("Left/right finger commands require six values")

        for index, motor_id in enumerate(INSPIRE_RIGHT_IDS):
            self.message.cmds[motor_id].q = float(right_command[index])
        for index, motor_id in enumerate(INSPIRE_LEFT_IDS):
            self.message.cmds[motor_id].q = float(left_command[index])

        try:
            self.publisher.Write(self.message)
            self.write_count += 1
        except Exception as exc:
            self.last_write_exception = exc
            raise

    def poll_state(self) -> Optional[np.ndarray]:
        message = self.subscriber.Read()
        if message is None:
            return self.last_state

        try:
            values = np.asarray(
                [
                    message.states[index].q
                    for index in range(INSPIRE_MOTOR_COUNT)
                ],
                dtype=float,
            )
        except Exception as exc:
            LOG.warning("Could not decode Inspire state: %s", exc)
            return self.last_state

        if np.isfinite(values).all():
            self.last_state = values
            self.last_state_time = time.monotonic()

        return self.last_state

    def state_age_s(self) -> float:
        if self.last_state_time <= 0.0:
            return math.inf
        return time.monotonic() - self.last_state_time

    def close(self) -> None:
        try:
            self.publisher.Close()
        except Exception:
            pass
        try:
            self.subscriber.Close()
        except Exception:
            pass


def wait_for_inspire_state(io: InspireDfxIo, timeout_s: float) -> None:
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        if io.poll_state() is not None:
            LOG.info("Inspire state feedback received.")
            return
        time.sleep(0.01)

    raise TimeoutError(
        f"No {INSPIRE_STATE_TOPIC} feedback within {timeout_s:.1f} seconds. "
        "Confirm inspire_g1 is running with LD_LIBRARY_PATH=/usr/local/lib."
    )



def _finger_process_main(
    config: dict[str, object],
    tracking_buffer: object,
    tracking_lock: object,
    tracking_motion_ready: object,
    tracking_received: object,
    tracking_sequence: object,
    mode_value: object,
    stop_event: object,
    ready_event: object,
    open_event: object,
    status_send: object,
) -> None:
    """Standalone-speed Inspire retargeting process.

    This process owns HandRetargeting and all Inspire DDS I/O. The parent owns
    the only TeleVuer instance and copies its latest landmarks through shared
    memory. Using the spawn start method avoids inheriting TeleVuer, arm IK,
    threads, or native optimizer state.
    """
    frequency_hz = float(config["frequency_hz"])
    command_speed_per_s = float(config["command_speed_per_s"])
    minimum_command = float(config["minimum_command"])
    stable_tracking_frames = int(config["stable_tracking_frames"])
    tracking_fault_frames = int(config["tracking_fault_frames"])
    tracking_stale_s = float(config["tracking_stale_s"])
    reacquire_command_tolerance = float(
        config["reacquire_command_tolerance"]
    )
    reacquire_stable_frames = int(config["reacquire_stable_frames"])
    feedback_stale_s = float(config["feedback_stale_s"])
    feedback_timeout_s = float(config["feedback_timeout_s"])
    network_interface = str(config["network_interface"])
    status_period_s = float(config.get("status_period_s", 0.25))

    io: Optional[InspireDfxIo] = None
    current_left = np.ones(6, dtype=float)
    current_right = np.ones(6, dtype=float)
    target_left = np.ones(6, dtype=float)
    target_right = np.ones(6, dtype=float)
    last_raw_left = np.full(6, np.nan, dtype=float)
    last_raw_right = np.full(6, np.nan, dtype=float)
    last_normalized_left = np.ones(6, dtype=float)
    last_normalized_right = np.ones(6, dtype=float)

    stable_count = 0
    fault_count = 0
    last_sequence = -1
    last_retarget_sequence = -1
    worker_loop_count = 0
    retarget_count = 0
    last_status_sent = 0.0
    tracking_reason = "waiting for Quest tracking"
    tracking_valid = False
    reacquire_ready = False
    reacquire_count = 0
    reacquire_max_error = math.inf
    previous_mode = FingerMode.OPEN
    feedback_fault = False
    worker_phase = "initializing"
    worker_error: Optional[str] = None

    def send_status(force: bool = False) -> None:
        nonlocal last_status_sent
        now = time.monotonic()
        if not force and now - last_status_sent < status_period_s:
            return

        status = {
            "mode": FingerMode(int(mode_value.value)),
            "worker_started": ready_event.is_set(),
            "worker_initializing": not ready_event.is_set(),
            "worker_phase": worker_phase,
            "worker_heartbeat_monotonic": now,
            "worker_age_s": 0.0,
            "worker_loop_count": worker_loop_count,
            "retarget_count": retarget_count,
            "tracking_valid": tracking_valid,
            "tracking_reason": tracking_reason,
            "reacquire_ready": reacquire_ready,
            "reacquire_count": reacquire_count,
            "reacquire_max_error": reacquire_max_error,
            "stable_count": stable_count,
            "fault_count": fault_count,
            "feedback_age_s": (
                math.inf if io is None else io.state_age_s()
            ),
            "feedback_fault": feedback_fault,
            "current_left": current_left.copy(),
            "current_right": current_right.copy(),
            "target_left": target_left.copy(),
            "target_right": target_right.copy(),
            "raw_left": last_raw_left.copy(),
            "raw_right": last_raw_right.copy(),
            "normalized_left": last_normalized_left.copy(),
            "normalized_right": last_normalized_right.copy(),
            "state": None if io is None else io.last_state,
            "write_count": 0 if io is None else io.write_count,
            "worker_error": worker_error,
            "process_pid": os.getpid(),
        }

        try:
            status_send.send(status)
            last_status_sent = now
        except (BrokenPipeError, EOFError, OSError):
            pass

    try:
        # The child is a fresh spawned interpreter, so DDS is initialized once
        # in this process and does not share the arm controller's runtime.
        ChannelFactoryInitialize(
            0,
            networkInterface=network_interface,
        )

        # Establish Inspire DDS feedback and a deterministic open pose before
        # loading the slower retargeting model.
        worker_phase = "opening-dds"
        send_status(force=True)
        io = InspireDfxIo()
        wait_for_inspire_state(io, feedback_timeout_s)

        for _ in range(10):
            io.publish(np.ones(6), np.ones(6))
            io.poll_state()
            time.sleep(0.02)

        open_event.set()

        # hand_retargeting.py expects teleop-relative assets. This chdir is
        # isolated to the spawned finger process.
        os.chdir(CURRENT_DIR)
        from teleop.robot_control.hand_retargeting import (
            HandRetargeting,
            HandType,
        )

        worker_phase = "loading-retargeting"
        send_status(force=True)
        retargeting = HandRetargeting(HandType.INSPIRE_HAND)

        ready_event.set()
        worker_phase = "ready"
        tracking_reason = "waiting for Quest tracking"
        send_status(force=True)
        LOG.info(
            "[FingerProcess] ready pid=%d; isolated retargeting loop %.1f Hz.",
            os.getpid(),
            frequency_hz,
        )

        last_loop = time.monotonic()
        tracking_fault_latched = False
        feedback_fault_latched = False
        reopen_after_feedback = False

        while not stop_event.is_set():
            loop_start = time.monotonic()
            worker_loop_count += 1
            dt = min(0.10, max(0.0, loop_start - last_loop))
            last_loop = loop_start

            mode = FingerMode(int(mode_value.value))
            if mode != previous_mode:
                reacquire_count = 0
                reacquire_ready = False
                reacquire_max_error = math.inf
                previous_mode = mode

            worker_phase = "feedback"
            state_values = io.poll_state()
            feedback_age = io.state_age_s()
            feedback_fault = feedback_age > feedback_stale_s

            if feedback_fault and not feedback_fault_latched:
                LOG.error(
                    "[FingerProcess] Inspire feedback stale: %.3f s; "
                    "holding commands until feedback returns.",
                    feedback_age,
                )
                feedback_fault_latched = True
                reopen_after_feedback = True
            elif not feedback_fault and feedback_fault_latched:
                LOG.warning(
                    "[FingerProcess] Inspire feedback recovered; opening "
                    "before following resumes."
                )
                feedback_fault_latched = False

            worker_phase = "tracking-copy"
            with tracking_lock:
                flat = np.frombuffer(
                    tracking_buffer,
                    dtype=np.float64,
                    count=150,
                ).copy()
                motion_ready = bool(tracking_motion_ready.value)
                received_monotonic = float(tracking_received.value)
                sequence = int(tracking_sequence.value)

            left_value = flat[:75].reshape(25, 3)
            right_value = flat[75:].reshape(25, 3)
            tracking_age = (
                loop_start - received_monotonic
                if received_monotonic > 0.0
                else math.inf
            )

            left_valid, left_hand, left_reason = finite_hand_landmarks(
                left_value
            )
            right_valid, right_hand, right_reason = finite_hand_landmarks(
                right_value
            )
            tracking_valid = (
                motion_ready
                and tracking_age <= tracking_stale_s
                and left_valid
                and right_valid
                and left_hand is not None
                and right_hand is not None
            )
            tracking_reason = (
                "ok"
                if tracking_valid
                else (
                    f"motion_ready={motion_ready}; "
                    f"age={tracking_age:.3f}s; "
                    f"left={left_reason}; right={right_reason}"
                )
            )

            if sequence != last_sequence:
                last_sequence = sequence
                if tracking_valid:
                    stable_count += 1
                    fault_count = 0
                    tracking_fault_latched = False
                else:
                    stable_count = 0
                    fault_count += 1

            if (
                mode == FingerMode.FOLLOW
                and fault_count >= tracking_fault_frames
                and not tracking_fault_latched
            ):
                LOG.warning(
                    "[FingerProcess] tracking lost; freezing finger commands. %s",
                    tracking_reason,
                )
                tracking_fault_latched = True

            effective_mode = mode
            if feedback_fault:
                effective_mode = FingerMode.HOLD
            elif reopen_after_feedback:
                effective_mode = FingerMode.OPEN
            elif (
                mode == FingerMode.FOLLOW
                and fault_count >= tracking_fault_frames
            ):
                effective_mode = FingerMode.HOLD
            elif mode == FingerMode.REACQUIRE:
                effective_mode = FingerMode.HOLD

            if mode == FingerMode.REACQUIRE:
                target_left = current_left.copy()
                target_right = current_right.copy()

            if (
                mode in (FingerMode.FOLLOW, FingerMode.REACQUIRE)
                and tracking_valid
                and not feedback_fault
            ):
                # Retarget only when the parent has supplied a fresh 30 Hz
                # TeleVuer frame. Publish/rate-limit at the configured rate between frames.
                if sequence != last_retarget_sequence:
                    assert left_hand is not None
                    assert right_hand is not None
                    last_retarget_sequence = sequence

                    ref_left = (
                        left_hand[retargeting.left_indices[1, :]]
                        - left_hand[retargeting.left_indices[0, :]]
                    )
                    ref_right = (
                        right_hand[retargeting.right_indices[1, :]]
                        - right_hand[retargeting.right_indices[0, :]]
                    )

                    worker_phase = "retarget-left"
                    send_status()
                    raw_left = (
                        retargeting.left_retargeting.retarget(ref_left)[
                            retargeting.left_dex_retargeting_to_hardware
                        ]
                    )

                    worker_phase = "retarget-right"
                    send_status()
                    raw_right = (
                        retargeting.right_retargeting.retarget(ref_right)[
                            retargeting.right_dex_retargeting_to_hardware
                        ]
                    )
                    retarget_count += 1

                    last_raw_left = np.asarray(
                        raw_left,
                        dtype=float,
                    ).copy()
                    last_raw_right = np.asarray(
                        raw_right,
                        dtype=float,
                    ).copy()

                    candidate_left = normalize_inspire_target(raw_left)
                    candidate_right = normalize_inspire_target(raw_right)
                    last_normalized_left = candidate_left.copy()
                    last_normalized_right = candidate_right.copy()

                    candidate_left = np.maximum(
                        candidate_left,
                        minimum_command,
                    )
                    candidate_right = np.maximum(
                        candidate_right,
                        minimum_command,
                    )

                    if mode == FingerMode.REACQUIRE:
                        reacquire_max_error = float(
                            max(
                                np.max(np.abs(candidate_left - current_left)),
                                np.max(np.abs(candidate_right - current_right)),
                            )
                        )
                        if (
                            reacquire_max_error
                            <= reacquire_command_tolerance
                        ):
                            reacquire_count += 1
                        else:
                            reacquire_count = 0
                        reacquire_ready = (
                            reacquire_count >= reacquire_stable_frames
                        )
                        target_left = current_left.copy()
                        target_right = current_right.copy()
                    else:
                        reacquire_count = 0
                        reacquire_ready = False
                        reacquire_max_error = 0.0
                        target_left = candidate_left
                        target_right = candidate_right
            elif effective_mode == FingerMode.OPEN:
                reacquire_count = 0
                reacquire_ready = False
                reacquire_max_error = math.inf
                target_left = np.ones(6, dtype=float)
                target_right = np.ones(6, dtype=float)
            else:
                target_left = current_left.copy()
                target_right = current_right.copy()

            if not feedback_fault:
                current_left = rate_limit_finger(
                    current_left,
                    target_left,
                    command_speed_per_s,
                    dt,
                )
                current_right = rate_limit_finger(
                    current_right,
                    target_right,
                    command_speed_per_s,
                    dt,
                )

                worker_phase = "publish"
                io.publish(current_left, current_right)

            fully_open = (
                float(np.min(current_left)) >= 0.995
                and float(np.min(current_right)) >= 0.995
            )
            if mode == FingerMode.OPEN and fully_open:
                open_event.set()
                reopen_after_feedback = False
            else:
                open_event.clear()

            worker_phase = "sleep"
            send_status()

            elapsed = time.monotonic() - loop_start
            stop_event.wait(
                max(0.0, 1.0 / frequency_hz - elapsed)
            )

    except BaseException as exc:
        worker_error = f"{type(exc).__name__}: {exc}"
        worker_phase = "failed"
        send_status(force=True)
        LOG.exception("[FingerProcess] fatal error")
    finally:
        # Best-effort final open independent of parent cleanup.
        if io is not None:
            try:
                deadline = time.monotonic() + 3.5
                last_publish = time.monotonic()
                while time.monotonic() < deadline:
                    now = time.monotonic()
                    dt = min(0.10, max(0.0, now - last_publish))
                    last_publish = now
                    current_left = rate_limit_finger(
                        current_left,
                        np.ones(6),
                        command_speed_per_s,
                        dt,
                    )
                    current_right = rate_limit_finger(
                        current_right,
                        np.ones(6),
                        command_speed_per_s,
                        dt,
                    )
                    io.publish(current_left, current_right)
                    if (
                        float(np.min(current_left)) >= 0.995
                        and float(np.min(current_right)) >= 0.995
                    ):
                        break
                    time.sleep(1.0 / frequency_hz)

                for _ in range(10):
                    io.publish(np.ones(6), np.ones(6))
                    time.sleep(0.02)
                open_event.set()
            except Exception:
                pass
            io.close()

        try:
            status_send.close()
        except Exception:
            pass


class FingerController:
    """Parent-side proxy for the isolated Inspire finger process."""

    def __init__(
        self,
        *,
        network_interface: str,
        frequency_hz: float,
        command_speed_per_s: float,
        minimum_command: float,
        stable_tracking_frames: int,
        tracking_fault_frames: int,
        tracking_stale_s: float,
        reacquire_command_tolerance: float,
        reacquire_stable_frames: int,
        feedback_stale_s: float,
        feedback_timeout_s: float,
    ) -> None:
        self._ctx = mp.get_context("spawn")
        self._tracking_buffer = self._ctx.Array(
            "d",
            150,
            lock=False,
        )
        self._tracking_lock = self._ctx.Lock()
        self._tracking_motion_ready = self._ctx.Value(
            "b",
            False,
            lock=False,
        )
        self._tracking_received = self._ctx.Value(
            "d",
            0.0,
            lock=False,
        )
        self._tracking_sequence = self._ctx.Value(
            "q",
            0,
            lock=False,
        )
        self._mode_value = self._ctx.Value(
            "i",
            FingerMode.OPEN.value,
            lock=False,
        )
        self._stop_event = self._ctx.Event()
        self._ready_event = self._ctx.Event()
        self._open_event = self._ctx.Event()
        self._status_recv, status_send = self._ctx.Pipe(duplex=False)

        self._status: dict[str, object] = {
            "mode": FingerMode.OPEN,
            "worker_started": False,
            "worker_initializing": True,
            "worker_phase": "process-starting",
            "worker_heartbeat_monotonic": 0.0,
            "worker_age_s": math.inf,
            "worker_loop_count": 0,
            "retarget_count": 0,
            "tracking_valid": False,
            "tracking_reason": "finger process is initializing",
            "reacquire_ready": False,
            "reacquire_count": 0,
            "reacquire_max_error": math.inf,
            "stable_count": 0,
            "fault_count": 0,
            "feedback_age_s": math.inf,
            "feedback_fault": False,
            "current_left": np.ones(6, dtype=float),
            "current_right": np.ones(6, dtype=float),
            "target_left": np.ones(6, dtype=float),
            "target_right": np.ones(6, dtype=float),
            "raw_left": np.full(6, np.nan, dtype=float),
            "raw_right": np.full(6, np.nan, dtype=float),
            "normalized_left": np.ones(6, dtype=float),
            "normalized_right": np.ones(6, dtype=float),
            "state": None,
            "write_count": 0,
            "worker_error": None,
            "process_pid": None,
        }

        config: dict[str, object] = {
            "network_interface": network_interface,
            "frequency_hz": frequency_hz,
            "command_speed_per_s": command_speed_per_s,
            "minimum_command": minimum_command,
            "stable_tracking_frames": stable_tracking_frames,
            "tracking_fault_frames": tracking_fault_frames,
            "tracking_stale_s": tracking_stale_s,
            "reacquire_command_tolerance": reacquire_command_tolerance,
            "reacquire_stable_frames": reacquire_stable_frames,
            "feedback_stale_s": feedback_stale_s,
            "feedback_timeout_s": feedback_timeout_s,
            "status_period_s": 0.20,
        }

        self._process = self._ctx.Process(
            target=_finger_process_main,
            args=(
                config,
                self._tracking_buffer,
                self._tracking_lock,
                self._tracking_motion_ready,
                self._tracking_received,
                self._tracking_sequence,
                self._mode_value,
                self._stop_event,
                self._ready_event,
                self._open_event,
                status_send,
            ),
            name="g1-inspire-finger-process",
            daemon=True,
        )
        self._process.start()
        status_send.close()

        LOG.info(
            "Finger process spawned pid=%s; retargeting preloads independently.",
            self._process.pid,
        )

    def update_tracking(self, tele_data: object) -> None:
        left_value = getattr(tele_data, "left_hand_pos", None)
        right_value = getattr(tele_data, "right_hand_pos", None)

        try:
            left = np.asarray(left_value, dtype=float)
        except Exception:
            left = np.zeros((25, 3), dtype=float)
        try:
            right = np.asarray(right_value, dtype=float)
        except Exception:
            right = np.zeros((25, 3), dtype=float)

        if left.shape != (25, 3):
            left = np.zeros((25, 3), dtype=float)
        if right.shape != (25, 3):
            right = np.zeros((25, 3), dtype=float)

        flat = np.concatenate(
            [left.reshape(-1), right.reshape(-1)]
        ).astype(np.float64, copy=False)

        with self._tracking_lock:
            shared = np.frombuffer(
                self._tracking_buffer,
                dtype=np.float64,
                count=150,
            )
            shared[:] = flat
            self._tracking_motion_ready.value = bool(
                getattr(tele_data, "motion_data_ready", False)
            )
            self._tracking_received.value = time.monotonic()
            self._tracking_sequence.value += 1

    def service_deferred(self) -> None:
        self._drain_status()

    def _drain_status(self) -> None:
        try:
            while self._status_recv.poll():
                status = self._status_recv.recv()
                if isinstance(status, dict):
                    self._status.update(status)
        except (EOFError, OSError):
            pass

        self._status["mode"] = FingerMode(int(self._mode_value.value))
        self._status["worker_started"] = self._ready_event.is_set()
        self._status["worker_initializing"] = (
            not self._ready_event.is_set()
            and self._process.is_alive()
        )

        heartbeat = float(
            self._status.get("worker_heartbeat_monotonic", 0.0)
        )
        self._status["worker_age_s"] = (
            time.monotonic() - heartbeat
            if heartbeat > 0.0
            else math.inf
        )

        if not self._process.is_alive():
            exitcode = self._process.exitcode
            if self._status.get("worker_error") is None:
                self._status["worker_error"] = (
                    f"finger process exited unexpectedly, exitcode={exitcode}"
                )
            self._status["worker_phase"] = "process-exited"

    def worker_started(self) -> bool:
        self._drain_status()
        return self._ready_event.is_set()

    def request_worker_start(self) -> None:
        # The process starts and preloads immediately at controller startup.
        self._drain_status()

    def set_mode(self, mode: FingerMode) -> None:
        self._mode_value.value = int(mode.value)

    def get_mode(self) -> FingerMode:
        return FingerMode(int(self._mode_value.value))

    def snapshot(self) -> dict[str, object]:
        self._drain_status()
        result: dict[str, object] = {}
        for key, value in self._status.items():
            result[key] = (
                value.copy() if isinstance(value, np.ndarray) else value
            )
        return result

    def alignment_ready(self) -> tuple[bool, str]:
        status = self.snapshot()
        if bool(status["worker_initializing"]):
            return False, "finger process is still initializing"
        if status["worker_error"] is not None:
            return False, str(status["worker_error"])
        if not bool(status["worker_started"]):
            return False, "finger process is not ready"
        if bool(status["feedback_fault"]):
            return False, (
                "Inspire feedback stale: "
                f"{float(status['feedback_age_s']):.3f} s"
            )
        if not bool(status["tracking_valid"]):
            return False, str(status["tracking_reason"])
        return True, "ok"

    def request_open_and_wait(self, timeout_s: float) -> bool:
        self._open_event.clear()
        self.set_mode(FingerMode.OPEN)
        return bool(
            self._open_event.wait(max(0.0, float(timeout_s)))
        )

    def close(self) -> None:
        """Stop the finger child with a bounded, deterministic shutdown.

        The child can be inside a native DDS Read() while it is still in the
        opening-dds startup phase. In that condition SIGTERM/join has proven
        capable of stalling controller shutdown. We therefore allow one short
        cooperative stop window, then use SIGKILL directly and continue.
        Final OPEN samples are published from the parent without waiting on
        Inspire feedback, so shutdown cannot block on another DDS Read().
        """
        self.set_mode(FingerMode.OPEN)
        self._stop_event.set()

        # Cooperative shutdown first. This is the normal path once the worker
        # has reached its regular loop.
        self._process.join(timeout=1.5)

        if self._process.is_alive():
            pid = self._process.pid
            LOG.error(
                "Finger process did not stop cooperatively; sending SIGKILL "
                "to pid=%s for deterministic shutdown.",
                pid,
            )
            if pid is not None:
                try:
                    os.kill(int(pid), signal.SIGKILL)
                except ProcessLookupError:
                    pass
                except Exception as exc:
                    LOG.error("Could not SIGKILL finger pid=%s: %s", pid, exc)

                # Reap directly without calling multiprocessing join() again;
                # the latter was the observed shutdown stall point.
                deadline = time.monotonic() + 0.75
                while time.monotonic() < deadline:
                    try:
                        waited_pid, _ = os.waitpid(int(pid), os.WNOHANG)
                    except ChildProcessError:
                        break
                    except Exception:
                        break
                    if waited_pid == int(pid):
                        break
                    time.sleep(0.02)

        # Independent final-open guarantee from the parent. Deliberately do
        # NOT create a subscriber or wait for feedback here: a blocked DDS Read
        # is exactly the startup failure mode this cleanup must survive.
        emergency_publisher: Optional[ChannelPublisher] = None
        try:
            emergency_publisher = ChannelPublisher(
                INSPIRE_COMMAND_TOPIC,
                MotorCmds_,
            )
            emergency_publisher.Init()
            message = MotorCmds_()
            message.cmds = [
                unitree_go_msg_dds__MotorCmd_()
                for _ in range(INSPIRE_MOTOR_COUNT)
            ]
            for motor_id in range(INSPIRE_MOTOR_COUNT):
                message.cmds[motor_id].q = 1.0
            for _ in range(10):
                emergency_publisher.Write(message)
                time.sleep(0.02)
            LOG.info("Parent published final Inspire open samples (no feedback wait).")
        except Exception as exc:
            LOG.error(
                "Parent final Inspire open publication failed: %s",
                exc,
            )
        finally:
            if emergency_publisher is not None:
                try:
                    emergency_publisher.Close()
                except Exception:
                    pass

        try:
            self._status_recv.close()
        except Exception:
            pass


def finger_mode_for_arm_state(state: State) -> FingerMode:
    if state == State.XR_ACTIVE:
        return FingerMode.FOLLOW
    if state == State.XR_TRACKING_HOLD:
        return FingerMode.REACQUIRE
    if state in (
        State.SAFETY_FAULT_HOLD,
        State.RETURN_ARMS_HOME,
        State.ARM_RAMP_DOWN,
    ):
        return FingerMode.HOLD
    return FingerMode.OPEN


def direct_child_pids(pid: int) -> list[int]:
    path = Path(f"/proc/{pid}/task/{pid}/children")
    try:
        content = path.read_text().strip()
    except (FileNotFoundError, PermissionError, ProcessLookupError):
        return []

    result: list[int] = []
    for token in content.split():
        try:
            child = int(token)
        except ValueError:
            continue
        if child > 1 and child != os.getpid():
            result.append(child)
    return result


def descendant_pids(root_pid: int) -> list[int]:
    ordered: list[int] = []
    seen: set[int] = set()
    stack = list(reversed(direct_child_pids(root_pid)))

    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        ordered.append(pid)
        stack.extend(reversed(direct_child_pids(pid)))

    return ordered


def process_label(pid: int) -> str:
    try:
        data = Path(f"/proc/{pid}/cmdline").read_bytes()
        label = data.replace(b"\0", b" ").decode(
            errors="replace"
        ).strip()
        return label or f"[pid {pid}]"
    except Exception:
        return f"[pid {pid}]"


DASHBOARD_CONTROLLER_PROCESS_PREFIX = (
    "g1_locomotion_xr_handover_live_v6_7_4_"
    "symmetric_thumb_control_dashboard_telemetry"
)


def same_user_dashboard_controller_pids(
    *,
    exclude_pids: Optional[set[int]] = None,
) -> list[int]:
    """Return same-user processes belonging to this dashboard-controller family.

    TeleVuer can fork helper processes that later detach/reparent to PID 1 while
    retaining the controller script in their inherited command line. Such
    helpers are no longer visible to ``descendant_pids(os.getpid())``.
    """
    excluded = set() if exclude_pids is None else set(exclude_pids)
    excluded.add(os.getpid())
    current_uid = os.geteuid()
    found: list[int] = []

    for proc_entry in Path("/proc").iterdir():
        if not proc_entry.name.isdigit():
            continue
        pid = int(proc_entry.name)
        if pid <= 1 or pid in excluded:
            continue

        try:
            if proc_entry.stat().st_uid != current_uid:
                continue
            raw = (proc_entry / "cmdline").read_bytes()
        except (FileNotFoundError, PermissionError, ProcessLookupError, OSError):
            continue

        matched = False
        for token in raw.split(b"\0"):
            if not token:
                continue
            try:
                name = Path(token.decode(errors="replace")).name
            except Exception:
                continue
            if name.startswith(DASHBOARD_CONTROLLER_PROCESS_PREFIX):
                matched = True
                break

        if matched:
            found.append(pid)

    return sorted(found)


def _process_start_ticks(pid: int) -> Optional[int]:
    """Return /proc starttime ticks (field 22), or None if unavailable."""
    try:
        text = Path(f"/proc/{pid}/stat").read_text()
        # comm is enclosed in parentheses and may contain spaces, so split only
        # after the final ')'. starttime is field 22 overall -> index 19 in the
        # remainder beginning with field 3 (state).
        remainder = text.rsplit(")", 1)[1].strip().split()
        return int(remainder[19])
    except (FileNotFoundError, PermissionError, ProcessLookupError, OSError,
            ValueError, IndexError):
        return None


def require_no_existing_dashboard_controller_processes() -> None:
    """Fail only for an older same-family process, not our own fork helpers.

    Some imported/native components can fork helper processes that inherit the
    full controller command line very early in startup. V1.2 treated those
    current-session helpers as a second controller and aborted. Helpers created
    by this launch have a start time >= this process, so ignore them here.

    The existing TCP-8012 bind guard remains authoritative before TeleVuer/arm
    command resources are created, so a concurrent real controller still cannot
    proceed into live ownership.
    """
    current_pid = os.getpid()
    current_start = _process_start_ticks(current_pid)
    own_descendants = set(descendant_pids(current_pid))

    candidates = same_user_dashboard_controller_pids(
        exclude_pids=own_descendants
    )
    existing: list[int] = []
    ignored_current_session: list[int] = []

    for pid in candidates:
        start = _process_start_ticks(pid)
        if (
            current_start is not None
            and start is not None
            and start >= current_start
        ):
            ignored_current_session.append(pid)
            continue
        existing.append(pid)

    if ignored_current_session:
        LOG.info(
            "V1.3 singleton guard: ignoring %d current-session helper(s): %s",
            len(ignored_current_session),
            ", ".join(str(pid) for pid in ignored_current_session),
        )

    if not existing:
        return

    details = ", ".join(
        f"{pid}:{process_label(pid)}" for pid in existing
    )
    raise RuntimeError(
        "An older dashboard telemetry controller/helper is still running: "
        f"{details}. Clean stale processes before starting a new controller."
    )


def kill_reparented_dashboard_controller_helpers() -> None:
    """SIGKILL detached/reparented helpers only after robot release is complete.

    Startup enforces a singleton controller, so any same-family process that
    remains at final cleanup is a helper leaked by this session (or a stale
    prior session). Arm ownership and finger resources are already released
    before this function is called.
    """
    for attempt in range(1, 4):
        stale = same_user_dashboard_controller_pids()
        if not stale:
            if attempt == 1:
                LOG.info(
                    "No detached/reparented dashboard-controller helpers remain."
                )
            return

        LOG.warning(
            "Detached helper cleanup pass %d: SIGKILL %d same-family "
            "process(es): %s",
            attempt,
            len(stale),
            ", ".join(
                f"{pid}:{process_label(pid)}" for pid in stale
            ),
        )
        for pid in stale:
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            except PermissionError as exc:
                LOG.warning(
                    "Could not SIGKILL detached helper pid=%d: %s",
                    pid,
                    exc,
                )
        time.sleep(0.15)

    survivors = same_user_dashboard_controller_pids()
    if survivors:
        LOG.error(
            "Detached/reparented dashboard-controller helpers still alive: %s",
            ", ".join(
                f"{pid}:{process_label(pid)}" for pid in survivors
            ),
        )
    else:
        LOG.info(
            "Detached/reparented dashboard-controller helper cleanup complete."
        )


def kill_all_descendants() -> None:
    root_pid = os.getpid()

    for attempt in range(1, 4):
        descendants = descendant_pids(root_pid)
        if not descendants:
            if attempt == 1:
                LOG.info("No remaining child processes.")
            return

        LOG.warning(
            "Shutdown pass %d: terminating %d descendant process(es): %s",
            attempt,
            len(descendants),
            ", ".join(
                f"{pid}:{process_label(pid)}"
                for pid in descendants
            ),
        )

        for pid in reversed(descendants):
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            except PermissionError as exc:
                LOG.warning(
                    "Could not kill descendant pid=%d: %s",
                    pid,
                    exc,
                )

        time.sleep(0.15)

    survivors = descendant_pids(root_pid)
    if survivors:
        LOG.error(
            "Descendant processes still alive: %s",
            ", ".join(
                f"{pid}:{process_label(pid)}"
                for pid in survivors
            ),
        )
    else:
        LOG.info("All descendant processes stopped.")



def _tcp_listener_socket_inodes(port: int) -> set[str]:
    """Return Linux socket inodes listening on the requested TCP port."""
    wanted_port = f"{int(port):04X}"
    inodes: set[str] = set()

    for proc_file in ("/proc/net/tcp", "/proc/net/tcp6"):
        try:
            lines = Path(proc_file).read_text().splitlines()[1:]
        except (FileNotFoundError, PermissionError, OSError):
            continue

        for line in lines:
            fields = line.split()
            if len(fields) < 10:
                continue

            local_address = fields[1]
            state = fields[3]
            inode = fields[9]

            try:
                local_port = local_address.rsplit(":", 1)[1].upper()
            except (IndexError, ValueError):
                continue

            # Linux TCP state 0A is LISTEN.
            if state == "0A" and local_port == wanted_port:
                inodes.add(inode)

    return inodes


def tcp_listener_pids(port: int) -> list[int]:
    """Find same-user processes that own a listening socket on a TCP port."""
    inodes = _tcp_listener_socket_inodes(port)
    if not inodes:
        return []

    wanted_links = {f"socket:[{inode}]" for inode in inodes}
    current_uid = os.geteuid()
    found: set[int] = set()

    for proc_entry in Path("/proc").iterdir():
        if not proc_entry.name.isdigit():
            continue

        pid = int(proc_entry.name)
        if pid <= 1:
            continue

        try:
            if proc_entry.stat().st_uid != current_uid:
                continue
        except (FileNotFoundError, PermissionError, ProcessLookupError):
            continue

        fd_dir = proc_entry / "fd"
        try:
            fd_entries = list(fd_dir.iterdir())
        except (FileNotFoundError, PermissionError, ProcessLookupError):
            continue

        for fd_entry in fd_entries:
            try:
                target = os.readlink(fd_entry)
            except (FileNotFoundError, PermissionError, ProcessLookupError, OSError):
                continue

            if target in wanted_links:
                found.add(pid)
                break

    return sorted(found)


def terminate_tcp_port_listeners(
    port: int,
    *,
    exclude_pids: Optional[set[int]] = None,
    term_timeout_s: float = 0.75,
    kill_timeout_s: float = 0.75,
    direct_kill: bool = False,
) -> bool:
    """Terminate detached same-user listener processes for a dedicated port.

    direct_kill is intentionally used for TeleVuer during final shutdown. The
    robot command publishers have already been released safely by that point;
    the remaining process is only the detached HTTPS/WebSocket listener.
    TeleVuer.close() and SIGTERM have both proven non-deterministic on this
    deployment, so SIGKILL is the deterministic server teardown path.
    """
    excluded = set() if exclude_pids is None else set(exclude_pids)
    excluded.add(os.getpid())

    def external_listener_pids() -> list[int]:
        return [
            pid
            for pid in tcp_listener_pids(port)
            if pid not in excluded
        ]

    pids = external_listener_pids()
    if not pids:
        LOG.info(
            "No detached process is listening on TCP port %d.",
            port,
        )
        return True

    if direct_kill:
        LOG.warning(
            "TCP port %d is still owned by detached TeleVuer listener(s): %s. "
            "Robot handback is complete; sending SIGKILL directly for "
            "deterministic server teardown.",
            port,
            ", ".join(
                f"{pid}:{process_label(pid)}"
                for pid in pids
            ),
        )
        survivors = pids
    else:
        LOG.warning(
            "TCP port %d is still owned by detached process(es): %s. "
            "Sending SIGTERM.",
            port,
            ", ".join(
                f"{pid}:{process_label(pid)}"
                for pid in pids
            ),
        )

        for pid in pids:
            try:
                os.kill(pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
            except PermissionError as exc:
                LOG.error(
                    "Cannot SIGTERM port-%d listener pid=%d: %s",
                    port,
                    pid,
                    exc,
                )

        deadline = time.monotonic() + max(0.0, term_timeout_s)
        while time.monotonic() < deadline:
            survivors = external_listener_pids()
            if not survivors:
                LOG.info(
                    "Detached TCP port %d listener stopped after SIGTERM.",
                    port,
                )
                return True
            time.sleep(0.05)

        survivors = external_listener_pids()
        if survivors:
            LOG.warning(
                "TCP port %d listener(s) ignored SIGTERM: %s. "
                "Sending SIGKILL.",
                port,
                ", ".join(
                    f"{pid}:{process_label(pid)}"
                    for pid in survivors
                ),
            )

    for pid in survivors:
        try:
            os.kill(pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        except PermissionError as exc:
            LOG.error(
                "Cannot SIGKILL port-%d listener pid=%d: %s",
                port,
                pid,
                exc,
            )

    deadline = time.monotonic() + max(0.0, kill_timeout_s)
    while time.monotonic() < deadline:
        survivors = external_listener_pids()
        if not survivors:
            LOG.info(
                "Detached TCP port %d listener stopped after SIGKILL.",
                port,
            )
            return True
        time.sleep(0.05)

    survivors = external_listener_pids()
    if survivors:
        LOG.error(
            "TCP port %d remains owned by: %s",
            port,
            ", ".join(
                f"{pid}:{process_label(pid)}"
                for pid in survivors
            ),
        )
        return False

    return True



def require_tcp_port_free(
    port: int = 8012,
    host: str = "0.0.0.0",
) -> None:
    """Fail only for a real listener/bind conflict, not TCP TIME_WAIT.

    TeleVuer/Vuer may require SIGKILL during shutdown. Connections from the
    previous HTTPS/WebSocket session can therefore remain in TIME_WAIT even
    after the listening process is gone. A probe with SO_REUSEADDR disabled
    incorrectly reports that normal TCP cleanup state as "port in use".

    First reject any actual LISTEN socket found in procfs. Then verify that a
    normal reusable server bind is possible, matching the semantics expected
    by asyncio/aiohttp on Linux.
    """
    listener_inodes = _tcp_listener_socket_inodes(port)
    if listener_inodes:
        owners = tcp_listener_pids(port)
        owner_text = (
            ", ".join(f"{pid}:{process_label(pid)}" for pid in owners)
            if owners
            else "listener owner not visible to this user"
        )
        raise RuntimeError(
            f"TCP port {port} has an active LISTEN socket ({owner_text}). "
            "Run: sudo ss -ltnp 'sport = :8012' ; "
            "sudo fuser -v 8012/tcp"
        )

    probe = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        # Allow immediate restart after the old TeleVuer listener has died.
        # TIME_WAIT connections are not active listeners and must not block
        # the next teleoperation process.
        probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        probe.bind((host, int(port)))
    except OSError as exc:
        raise RuntimeError(
            f"TCP port {port} cannot be rebound even though no LISTEN socket "
            "was found. Run: sudo ss -ltnp 'sport = :8012' ; "
            "sudo ss -tanp | grep ':8012' ; sudo fuser -v 8012/tcp"
        ) from exc
    finally:
        probe.close()



