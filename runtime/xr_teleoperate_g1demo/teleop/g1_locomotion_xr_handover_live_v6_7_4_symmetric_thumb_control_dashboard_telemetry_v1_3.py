@dataclass
class RemoteState:
    valid: bool = False
    keys: int = 0
    lx: float = math.nan
    ly: float = math.nan
    rx: float = math.nan
    ry: float = math.nan

    @property
    def max_abs_axis(self) -> float:
        axes = np.asarray(
            [self.lx, self.ly, self.rx, self.ry],
            dtype=float,
        )
        if not np.isfinite(axes).all():
            return math.nan
        return float(np.max(np.abs(axes)))


