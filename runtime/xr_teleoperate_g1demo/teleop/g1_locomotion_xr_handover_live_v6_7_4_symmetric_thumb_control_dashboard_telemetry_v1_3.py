#!/usr/bin/env python3
"""Live G1 Regular-mode locomotion <-> XR arm handover (V6.7.4 symmetric thumb control).

THIS PROGRAM PUBLISHES REAL ARM COMMANDS TO ``rt/arm_sdk`` AND REAL
INSPIRE DFX COMMANDS TO ``rt/inspire/cmd``.

Merged from verified sources:
- arm V4 SHA-256: 915118ee63dffbd0e820aeb116105a70e0fac36bf72a5755d53acb6335f49b67
- finger V5 SHA-256: dbc9c43dcc1ddb98bbc9ad8c508140cd519b4ab3b76e9517a6cb68f70ee0260e

Architecture
------------
LOCOMOTION_READY
    Unitree Regular mode owns legs, waist, balance, and arms.
    The R3 operator may move the robot.

WAITING_FOR_STOP
    R3 sticks must be neutral and LowState must indicate that the lower body
    has settled for the configured hold time.

XR_ALIGNMENT
    The VR operator matches the current robot arm pose. One common XYZ
    translation is registered for both wrists.

ARM_RAMP_UP
    Live head-yaw-relative XR targets are solved by IK while arm ownership is
    ramped smoothly from zero to ``--teleop-weight``.

XR_ACTIVE
    The XR operator controls both arms and both Inspire DFX hands. Fingers run
    in a dedicated configurable-rate worker while the arm safety loop remains separate.

ARM_RAMP_DOWN
    XR is frozen at the last safe arm target and ownership is blended smoothly
    to zero. No artificial q=0 pose is inserted; Regular mode takes over
    continuously during the weight ramp.

Safety model
------------
- R3 movement during XR control freezes the XR command and enters a fault hold.
- Sustained lower-body movement during XR control also enters a fault hold.
- Lost XR/hand tracking freezes the current arm and finger commands without
  entering safety-fault mode. Arm control resumes after both wrists return near
  the frozen pose for several stable frames. Finger commands remain frozen and
  reacquire independently until the tracked finger pose matches safely.
- Wrist jump rejection is bimanually coherent: if either wrist is rejected,
  BOTH wrist targets hold the last coherent pair. A persistent discontinuity
  enters XR_TRACKING_HOLD; a distant pose is never auto-accepted just because
  it remains stable. One stale wrist is never mixed with one fresh wrist.
- Every successful XR alignment clears the stateful IK smoothing history so
  repeated c-toggle sessions do not inherit joint solutions from prior sessions.
- Tracking-hold recovery preserves the pre-hold IK smoothing history so the
  first resumed solve remains continuous with the frozen safe target; the
  existing IK discontinuity guard remains active.
- Synchronized per-loop diagnostics record XR, guarded Cartesian targets, IK,
  published arm targets, measured joints, torque estimate, temperatures, and
  motor state in one CSV generated by this controller process.
- Stale Inspire feedback freezes finger commands and faults active XR control.
- Left and right thumb-rotation channels both follow their retargeted six-channel hand commands.
- The current TeleVuer hand stream may retain its last valid hand sample when
  hands are hidden. Therefore, hand hiding is NOT treated as a guaranteed
  emergency-stop mechanism.
- ``c`` is a mode/handover command, not an emergency stop.
- The R3 operator must retain immediate access to the robot's verified damping
  or emergency-stop procedure.

Keys
----
c : request XR mode, cancel a pending request, or request handback
p : print a detailed status snapshot
q : perform a controlled handback and exit

Use only the locally served Quest page:
    https://192.168.0.116:8012/?ws=wss://192.168.0.116:8012
"""

